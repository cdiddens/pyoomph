  // A single link from an element to an "external" (i.e. not one of its own nodal/internal) Data object,
  // e.g. a coupling to a value living on another domain/mesh, or a global parameter exposed as Data.
  class ExternalDataLink
  {
  public:
    oomph::Data *data;   // External data object
    int value_index;     // Value of this external data to be taken
    int elemental_index; // Index of the external_data_pt inside the element
    ExternalDataLink(oomph::Data *d, int v) : data(d), value_index(v), elemental_index(-1) {}
  };

  // Collection of ExternalDataLinks for one DynamicJITCode, with deduplication of the
  // underlying Data pointers so that each distinct external Data object is only added once per element.
  class ExternalDataLinkVector : public std::vector<ExternalDataLink>
  {
  protected:
    std::vector<oomph::Data *> elemental_data; // Deduplicated list of Data objects that must be registered as external data on the element

  public:
    ExternalDataLinkVector() {}
    ExternalDataLinkVector(unsigned n) : std::vector<ExternalDataLink>(n, ExternalDataLink(NULL, -1)) {}
    // Rebuilds elemental_data from the (possibly sparsely filled) link entries, removing duplicates.
    // field_contribution_index is the ED0 array parallel to these links: a field marked -2 takes part
    // in no contribution of the code, i.e. it is read by output/integral expressions only. Such a link
    // is not registered as element external data - it would add a dof to every element of the domain,
    // and with it a row and a column of the dense elemental Jacobian, that no residual ever writes.
    // Its elemental_index stays -1 unless some assembly-relevant link shares the same Data object, and
    // fill_element_info reads the value straight from the Data in that case.
    void reindex_elemental_data(const int *field_contribution_index = NULL);
    std::vector<oomph::Data *> &get_required_external_data() { return elemental_data; }
  };



  // One JIT-compiled equation code: a single shared library generated by the JIT code generator
  // (GiNaC symbolic equations -> C code -> compiled .so) from one FiniteElementCode (a bulk domain
  // or an interface), loaded into this process and bound to the bulk mesh it was compiled for.
  // This used to be two classes - DynamicBulkElementCode (the loaded .so) and
  // DynamicBulkElementInstance (a per-mesh binding of it) - on the assumption that one compiled
  // library would be instantiated on several meshes. That never happened: exactly one binding was
  // ever created per loaded library, so the second class was a pure forwarding facade, and its
  // get_code() (returning the .so wrapper) sitting next to the other one's get_code() (returning
  // the symbolic code generator) was a standing trap. Hence the merge.
  class DynamicJITCode
  {
  protected:
    friend class Problem;
    friend class FiniteElementCode;
    friend class BulkElementBase;
    Problem *problem;
    CCompiler *compiler;
    std::string filename;
    JITFuncSpec_Table_FiniteElement_t *functable; // Function table exported by the compiled .so, containing all residual/jacobian/etc. callbacks
    FiniteElementCode *code_gen; // The symbolic (GiNaC-based) code generator this binary was compiled from
    std::map<std::string, int> integral_function_map, extremum_function_map; // Name -> index lookup for integral/extremum diagnostic functions exposed by the code
    void *so_handle; // dlopen() handle of the loaded shared library
    ExternalDataLinkVector linked_external_data;
    pyoomph::Mesh *bulkmesh; // Bulk mesh -> required to identify interface field indices

  public:
    // Indices whose bulk residual contribution a continuous space should have nullified at an
    // interface (negative = position dof). Part of a feature that has never been switched on:
    // nothing fills this set, and its only reader, InterfaceMesh::nullify_selected_bulk_dofs(),
    // throws outright. The constructor code that used to populate it from the function table's
    // nullified_bulk_residuals had been commented out for just as long and is gone with the merge.
    std::set<int> nullify_bulk_residuals;
    DynamicJITCode(Problem *prob, CCompiler *ccompiler, std::string fnam, FiniteElementCode *cg, pyoomph::Mesh *bm);
    virtual ~DynamicJITCode(); // Closes the shared library handle
    const std::string &get_file_name() const { return filename; }
    FiniteElementCode *get_code_gen() { return code_gen; }
    Problem *get_problem() { return problem; }
    pyoomph::Mesh *get_bulk_mesh() { return bulkmesh; }
    void set_bulk_mesh(pyoomph::Mesh *m) { bulkmesh = m; }
    const JITFuncSpec_Table_FiniteElement_t *get_func_table() const { return functable; }
    JITFuncSpec_Table_FiniteElement_t *get_func_table() { return functable; }
    int get_max_dt_order() const { return functable->max_dt_order; }
    int get_integral_function_index(std::string n); // -1 if not present
    int get_extremum_function_index(std::string n); // -1 if not present
    unsigned _set_solved_residual(std::string name);
    void link_external_data(std::string name, oomph::Data *data, int index, std::string full_source_name);
    std::map<std::string, unsigned> setup_interface_dof_indices(); // Populates the interface_dof_indices array in the space_info of the functable. This is required for continuous fields (C2TB-C1) to identify the additional dofs on interface nodes
    void sanity_check(); // Consistency checks of the field/external-data setup against the compiled function table; throws on failure
    bool has_parameter_contribution(const std::string &param); // Whether the compiled code has a (residual/jacobian) contribution depending on the given global parameter
    bool can_be_time_adaptive() const { return functable->has_temporal_estimators; }
    unsigned int get_num_global_parameters() const { return functable->numglobal_params; }
    int get_nodal_field_index(std::string name);
    std::map<std::string, unsigned> get_nodal_field_indices();
    std::map<std::string, unsigned> get_elemental_field_indices();
    int get_discontinuous_field_index(std::string name);
    unsigned resolve_interface_dof_id(std::string n);
    std::string get_space_of_field(std::string name);
    bool has_moving_nodes() { return functable->moving_nodes; }
    ExternalDataLinkVector &get_linked_external_data() { return linked_external_data; }
  };

